"""Image generation for the storybook pipeline.

Story text is generated by Gemini in agent.py/story_generator.py.
Illustrations are generated by Replicate's Google Imagen 4 model.
Imagen 4 on Replicate accepts text prompts (not a reference-image input),
so character consistency is encouraged with a shared, detailed character bible
included verbatim in every page prompt.
"""

from __future__ import annotations

import os
import re
from io import BytesIO
from pathlib import Path
from urllib.request import Request, urlopen

from dotenv import load_dotenv
from PIL import Image, ImageDraw

load_dotenv()


def safe_filename(value: str) -> str:
    """Convert a name into a simple, filesystem-safe filename."""
    value = re.sub(r"[^a-zA-Z0-9_-]+", "_", value.strip())
    return value.strip("_") or "storybook"


def validate_image(path: str | Path) -> Path:
    """Verify that an image exists and can be decoded by Pillow."""
    image_path = Path(path)
    if not image_path.is_file():
        raise FileNotFoundError(f"Image not found: {image_path}")

    try:
        with Image.open(image_path) as image:
            image.verify()
        with Image.open(image_path) as image:
            if image.width < 1 or image.height < 1:
                raise ValueError("Image has invalid dimensions.")
    except Exception as exc:
        raise ValueError(f"Invalid image file: {image_path}") from exc

    return image_path


def create_demo_image(
    output_path: str | Path,
    title: str,
    description: str,
) -> Path:
    """Create a clearly labelled placeholder for offline/demo testing only."""
    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    image = Image.new("RGB", (768, 1024), "#fff8e8")
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle(
        (30, 30, 738, 994), radius=24, outline="#6b705c", width=4
    )
    draw.text((60, 70), title[:80], fill="#333333")

    words = description.split()
    lines: list[str] = []
    current_line = ""
    for word in words:
        candidate = f"{current_line} {word}".strip()
        if len(candidate) > 42:
            if current_line:
                lines.append(current_line)
            current_line = word
        else:
            current_line = candidate
    if current_line:
        lines.append(current_line)

    y = 150
    for line in lines[:23]:
        draw.text((60, y), line, fill="#555555")
        y += 30

    draw.text(
        (60, 930),
        "DEMO PLACEHOLDER - NOT AN AI ILLUSTRATION",
        fill="#9b2226",
    )
    image.save(output_path, format="PNG")
    return validate_image(output_path)


def _output_to_bytes(output: object) -> bytes:
    """Normalize the different output shapes returned by Replicate clients."""
    if isinstance(output, (list, tuple)):
        if not output:
            raise RuntimeError("Replicate returned an empty image output.")
        output = output[0]  # Imagen 4 is expected to return one image.

    if isinstance(output, (bytes, bytearray, memoryview)):
        return bytes(output)

    # Current Replicate Python client versions expose generated files through
    # FileOutput.read(); model/API versions may instead return a URL string.
    read_method = getattr(output, "read", None)
    if callable(read_method):
        data = read_method()
        if isinstance(data, (bytes, bytearray, memoryview)) and data:
            return bytes(data)
        raise RuntimeError("Replicate returned an empty file output.")

    url = output if isinstance(output, str) else getattr(output, "url", None)
    if callable(url):
        url = url()
    if isinstance(url, str) and url.startswith(("https://", "http://")):
        request = Request(url, headers={"User-Agent": "storybook-agent/1.0"})
        try:
            with urlopen(request, timeout=120) as response:
                data = response.read()
        except Exception as exc:
            raise RuntimeError("Could not download the generated image from Replicate.") from exc
        if not data:
            raise RuntimeError("Replicate returned an empty image download.")
        return data

    raise RuntimeError(
        "Unsupported Replicate output type. Expected a file output or image URL; "
        f"received {type(output).__name__}."
    )


def generate_image(
    prompt: str,
    output_path: str | Path,
    reference_path: str | Path | None = None,
) -> Path:
    """Generate one image with Replicate Imagen 4 and save it as a PNG.

    ``reference_path`` remains in the signature for compatibility with the
    previous Gemini implementation. Imagen 4's Replicate schema does not take
    reference images as inputs, so this file is validated but not sent to the
    API. Keep character details in the prompt for repeatable visual guidance.
    """
    if not prompt or not prompt.strip():
        raise ValueError("Image prompt must not be empty.")

    api_token = os.getenv("REPLICATE_API_TOKEN", "").strip()
    if not api_token:
        raise RuntimeError(
            "REPLICATE_API_TOKEN is missing. Add it to your .env file."
        )

    if reference_path is not None:
        validate_image(reference_path)

    try:
        import replicate
    except ImportError as exc:
        raise RuntimeError(
            "The Replicate Python package is not installed. Run: pip install replicate"
        ) from exc

    model = os.getenv("REPLICATE_IMAGE_MODEL", "google/imagen-4").strip()
    image_size = os.getenv("REPLICATE_IMAGE_SIZE", "1K").strip()
    aspect_ratio = os.getenv("REPLICATE_IMAGE_ASPECT_RATIO", "3:4").strip()
    output_format = os.getenv("REPLICATE_IMAGE_OUTPUT_FORMAT", "jpg").strip().lower()
    safety_filter_level = os.getenv(
        "REPLICATE_SAFETY_FILTER_LEVEL", "block_medium_and_above"
    ).strip()

    if output_format not in {"jpg", "png"}:
        raise ValueError(
            "REPLICATE_IMAGE_OUTPUT_FORMAT must be 'jpg' or 'png'."
        )

    output_path = Path(output_path)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    model_input = {
        "prompt": prompt.strip(),
        "image_size": image_size,
        "aspect_ratio": aspect_ratio,
        "output_format": output_format,
        "safety_filter_level": safety_filter_level,
    }

    print(f"Requesting image from Replicate model {model}...", flush=True)
    try:
        output = replicate.run(model, input=model_input)
        image_bytes = _output_to_bytes(output)
    except Exception as exc:
        # Avoid hiding the provider's useful error text (quota, auth, model input).
        if isinstance(exc, RuntimeError) and str(exc).startswith(
            ("Replicate returned", "Could not download", "Unsupported Replicate")
        ):
            raise
        raise RuntimeError(f"Replicate image generation failed: {exc}") from exc

    # Standardize generated image files to PNG. This keeps filenames consistent
    # and makes the PDF stage independent of the provider's selected output format.
    try:
        with Image.open(BytesIO(image_bytes)) as generated:
            generated.load()
            if generated.mode not in {"RGB", "RGBA"}:
                generated = generated.convert("RGB")
            generated.save(output_path, format="PNG", optimize=True)
    except Exception as exc:
        raise RuntimeError(
            "Replicate returned data that Pillow could not decode as an image."
        ) from exc

    validate_image(output_path)
    print(f"Image saved: {output_path}", flush=True)
    return output_path


def _character_bible(character) -> str:
    """Build the shared identity description used by all image prompts."""
    features = ", ".join(character.signature_features)
    return (
        f"Name: {character.name}.\n"
        f"Species: {character.species}.\n"
        f"Appearance: {character.appearance}.\n"
        f"Personality: {character.personality}.\n"
        f"Signature visual features that must not change: {features}."
    )


def build_character_prompt(character) -> str:
    """Build a character reference prompt for Imagen 4."""
    return f"""
Create a polished character-design illustration for a children's picture book.

MAIN CHARACTER IDENTITY — preserve every detail:
{_character_bible(character)}

Show one full-body view of this character, centered and unobstructed, in a
simple light background. Make the face, body proportions, colors, clothing,
and all signature features very clear. Use a charming, colorful, hand-painted
storybook illustration style, soft lighting, clean shapes, and child-friendly
visuals. This image establishes the character design to describe consistently
in the later page prompts.

Do not include text, labels, a character sheet grid, logos, or watermarks.
""".strip()


def build_scene_prompt(character, page) -> str:
    """Build a scene prompt with the same character identity text every time."""
    return f"""
Create the illustration for page {page.page_number} of a children's picture book.

MAIN CHARACTER IDENTITY — use exactly this design; do not redesign the character:
{_character_bible(character)}

SCENE: {page.scene_description}
CHARACTER ACTION: {page.character_action}
ENVIRONMENT: {page.environment}
MOOD: {page.mood}

Continuity requirements:
- Depict the same individual described in MAIN CHARACTER IDENTITY.
- Keep the character's species, face, eye color, fur/skin colors, proportions,
  clothing, accessories, and signature features unchanged.
- Change only pose, expression, and viewing angle as needed for this scene.
- If other characters appear, make them visually distinct from the main character.
- Keep the important action and setting clear at a glance.

Style: polished, colorful, warm children's picture-book illustration, expressive
faces, soft painterly texture, coherent lighting, attractive composition.
No text, captions, speech bubbles, logos, frames, or watermarks.
""".strip()


def generate_character_reference(
    character,
    output_dir: str | Path = "outputs",
    demo_mode: bool = False,
) -> Path:
    """Generate the main character reference image, or a demo placeholder."""
    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    output_path = directory / f"{safe_filename(character.name)}_reference.png"

    if demo_mode:
        return create_demo_image(
            output_path,
            f"Character reference: {character.name}",
            (
                f"{character.species}. {character.appearance}. "
                f"Features: {', '.join(character.signature_features)}"
            ),
        )

    return generate_image(
        prompt=build_character_prompt(character),
        output_path=output_path,
    )


def generate_page_illustrations(
    story_plan,
    reference_path: str | Path,
    output_dir: str | Path = "outputs",
    demo_mode: bool = False,
) -> list[Path]:
    """Generate exactly five page images from the story plan.

    The reference image is validated and saved as part of the deliverables, but
    Imagen 4's current Replicate input schema does not accept image references.
    Each page prompt therefore repeats the same structured character identity.
    """
    if len(story_plan.pages) != 5:
        raise ValueError("A storybook must contain exactly five pages.")

    directory = Path(output_dir)
    directory.mkdir(parents=True, exist_ok=True)
    validate_image(reference_path)

    generated_paths: list[Path] = []
    if not demo_mode:
        print(
            "Imagen 4 uses text prompts here; reusing the character identity "
            "description for each page.",
            flush=True,
        )

    for page in story_plan.pages:
        output_path = directory / f"page_{page.page_number}.png"
        print(
            f"Generating illustration {page.page_number}/5...", flush=True
        )

        if demo_mode:
            image_path = create_demo_image(
                output_path,
                f"Page {page.page_number}: {story_plan.title}",
                f"{page.narrative_text} Scene: {page.scene_description}",
            )
        else:
            image_path = generate_image(
                prompt=build_scene_prompt(story_plan.character, page),
                output_path=output_path,
            )
        generated_paths.append(image_path)

    if len(generated_paths) != 5:
        raise RuntimeError(
            f"Expected exactly five page illustrations, got {len(generated_paths)}."
        )
    return generated_paths
